"""Converts fixed-width BDF fonts to C for edgenoded's screen.

Usage: bdf2c.py NAME=FONT.bdf [NAME=FONT.bdf ...] > fonts.c

Each NAME becomes a `const struct font NAME` (font.h) holding printable
ASCII (0x20-0x7e), one uint16_t per glyph row with the leftmost pixel in
bit 15. The fonts' COMMENT lines, which carry their copyright and license,
are kept at the top of the output.
"""

import sys

FIRST, LAST = 0x20, 0x7E


def parse(path):
    comments, glyphs = [], {}
    box = None
    with open(path, encoding="ascii") as f:
        lines = iter(f.read().splitlines())
    for line in lines:
        key, _, rest = line.partition(" ")
        if key == "COMMENT":
            comments.append(rest)
        elif key == "FONTBOUNDINGBOX":
            box = tuple(int(v) for v in rest.split())
        elif key == "STARTCHAR":
            encoding, bbx, rows = None, None, []
            for line in lines:
                key, _, rest = line.partition(" ")
                if key == "ENCODING":
                    encoding = int(rest.split()[0])
                elif key == "BBX":
                    bbx = tuple(int(v) for v in rest.split())
                elif key == "BITMAP":
                    for line in lines:
                        if line == "ENDCHAR":
                            break
                        rows.append(line.strip())
                    break
            if encoding is not None and FIRST <= encoding <= LAST:
                glyphs[encoding] = (bbx, rows)
    if box is None:
        sys.exit(f"{path}: no FONTBOUNDINGBOX")
    return comments, box, glyphs


def comment_text(comments):
    """COMMENT lines without their own C comment markers, safe inside one."""
    for c in comments:
        c = c.strip()
        if c in ("/*", "*/"):
            continue
        if c.startswith("*"):
            c = c[1:].strip()
        yield c.replace("*/", "* /")


def cell_rows(path, box, code, glyph):
    """The glyph placed in the font's cell, as width-bit rows from the top."""
    width, height, box_x, box_y = box
    ascent = height + box_y
    (gw, gh, gx, gy), bitmap = glyph
    top, left = ascent - (gy + gh), gx - box_x
    if len(bitmap) != gh or top < 0 or left < 0 or top + gh > height or left + gw > width:
        sys.exit(f"{path}: glyph 0x{code:02x} does not fit the font's cell")
    rows = [0] * height
    for y, text in enumerate(bitmap):
        bits, value = len(text) * 4, int(text, 16)
        for x in range(gw):
            if value >> (bits - 1 - x) & 1:
                rows[top + y] |= 1 << (15 - left - x)
    return rows


def main(args):
    if not args:
        sys.exit(__doc__)
    out = ["/* Generated by bdf2c.py: do not edit. */", ""]
    body = []
    for arg in args:
        name, sep, path = arg.partition("=")
        if not sep or not name.isidentifier():
            sys.exit(f"expected NAME=FONT.bdf, got {arg!r}")
        comments, box, glyphs = parse(path)
        width, height, _, box_y = box
        if width > 16:
            sys.exit(f"{path}: wider than 16 pixels")
        missing = [f"0x{c:02x}" for c in range(FIRST, LAST + 1) if c not in glyphs]
        if missing:
            sys.exit(f"{path}: no glyph for {', '.join(missing)}")

        out += [f"/* {name}, from {path.rsplit('/', 1)[-1]}:"] + [
            f" * {c}".rstrip() for c in comment_text(comments)
        ] + [" */", ""]
        body.append(f"static const uint16_t {name}_rows[{LAST - FIRST + 1}][{height}] = {{")
        for code in range(FIRST, LAST + 1):
            rows = cell_rows(path, box, code, glyphs[code])
            body.append(f"\t{{ {', '.join(f'0x{r:04x}' for r in rows)} }},")
        body += [
            "};",
            "",
            f"const struct font {name} = {{",
            f"\t.width = {width},",
            f"\t.height = {height},",
            f"\t.ascent = {height + box_y},",
            f"\t.first = 0x{FIRST:02x},",
            f"\t.count = {LAST - FIRST + 1},",
            f"\t.rows = &{name}_rows[0][0],",
            "};",
            "",
        ]
    print("\n".join(out + ['#include "font.h"', ""] + body), end="")


if __name__ == "__main__":
    main(sys.argv[1:])
